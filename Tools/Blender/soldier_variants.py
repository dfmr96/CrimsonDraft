# CLI
# ---------------------------------------------------------------------------------------------
def main(argv):
    p = argparse.ArgumentParser(prog="soldier_variants")
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--force", action="store_true")
    b.add_argument("--no-blockouts", action="store_true")
    sub.add_parser("blockouts")
    n = sub.add_parser("new-variant")
    n.add_argument("--from", dest="src", required=True)
    n.add_argument("--name", required=True)
    sub.add_parser("validate")
    sub.add_parser("export")
    a = p.parse_args(argv)

    if a.cmd == "build":
        build(force=a.force, blockouts=not a.no_blockouts)
    elif a.cmd == "blockouts":
        make_blockouts()
        bpy.ops.wm.save_mainfile()
    elif a.cmd == "new-variant":
        new_variant(a.src, a.name)
        bpy.ops.wm.save_mainfile()
    elif a.cmd == "validate":
        validate()
    elif a.cmd == "export":
        export()


if __name__ == "__main__" and "--" in sys.argv:
    try:
        main(sys.argv[sys.argv.index("--") + 1:])
    except PipelineError as e:
        print("[soldier_variants] ERROR: %s" % e)
        sys.exit(1)
