def build(force=False, blockouts=True):
    if os.path.exists(BLEND) and not force:
        raise PipelineError("%s already exists (it may contain hand-made variants). Use --force to rebuild." % BLEND)

    bpy.ops.wm.read_factory_settings(use_empty=True)
    # Work on a temporary copy so the asset in Unity is never opened for writing.
    tmp = os.path.join(tempfile.mkdtemp(prefix="soldier_variants_"), os.path.basename(SOURCE_FBX))
    shutil.copy2(SOURCE_FBX, tmp)
    bpy.ops.import_scene.fbx(filepath=tmp, **IMPORT_SETTINGS)

    arm = rig()
    arm.animation_data_clear()
    for a in list(bpy.data.actions):
        bpy.data.actions.remove(a)
    for pb in arm.pose.bones:
        pb.matrix_basis = Matrix.Identity(4)

    ref = bpy.data.collections.new(REFERENCE_COLLECTION)
    bpy.context.scene.collection.children.link(ref)
    move_to_collection(body(), ref)
    move_to_collection(arm, bpy.context.scene.collection)

    for legacy, new_name in LEGACY.items():
        obj = bpy.data.objects.get(legacy)
        if not obj:
            raise PipelineError("Piece '%s' not found in the source FBX." % legacy)
        bake_transform_into_mesh(obj, arm)
        obj.name = obj.data.name = new_name
        ensure_armature_modifier(obj, arm)
        limit_and_normalize(obj)
        move_to_collection(obj, slot_collection(slot_of(new_name)))

    if blockouts:
        make_blockouts()

    bpy.ops.wm.save_as_mainfile(filepath=BLEND)
    log("Saved %s" % BLEND)


def new_variant(from_name, variant, slot=None):
    """Duplicates an existing variant (mesh, weights, material, Armature modifier) as <Slot>_<variant>.
    After this only the shape needs modelling; re-run validate/export."""
    src = bpy.data.objects.get(from_name)
    if not src:
        raise PipelineError("Variant '%s' not found." % from_name)
    slot = slot or slot_of(from_name)
    if slot not in SLOTS:
        raise PipelineError("Unknown slot for '%s'." % from_name)
    name = "%s_%s" % (slot, variant)
    if bpy.data.objects.get(name):
        raise PipelineError("'%s' already exists." % name)
    obj = src.copy()
    obj.data = src.data.copy()
    obj.name = obj.data.name = name
    slot_collection(slot).objects.link(obj)
    ensure_armature_modifier(obj, rig())
    log("Created %s from %s" % (name, from_name))
    return obj


def _new_mesh_object(name, bm, material, uv_from):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    obj = bpy.data.objects.new(name, me)
    slot_collection(slot_of(name)).objects.link(obj)
    arm = rig()
    obj.parent = arm
    obj.matrix_parent_inverse = Matrix.Identity(4)
    me.materials.append(material)
    _box_uv_into_rect(obj, uv_rect(uv_from))
    ensure_armature_modifier(obj, arm)
    return obj


def _box_uv_into_rect(obj, rect):
    """Cheap UV: front projection normalized into the source piece's atlas rect."""
    me = obj.data
    uv = me.uv_layers.new(name="UVMap") if not me.uv_layers else me.uv_layers.active
    lo, hi = mesh_bounds(obj)
    u0, v0, u1, v1 = rect
    for poly in me.polygons:
        for li in poly.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            fx = (co.x - lo.x) / max(hi.x - lo.x, 1e-6)
            fz = (co.z - lo.z) / max(hi.z - lo.z, 1e-6)
            uv.data[li].uv = (u0 + fx * (u1 - u0), v0 + fz * (v1 - v0))


def _scaled_copy(src_name, variant, scale, anchor):
    obj = new_variant(src_name, variant)
    m = Matrix.Translation(anchor) @ Matrix.Diagonal((*scale, 1.0)) @ Matrix.Translation(-anchor)
    obj.data.transform(m)
    return obj


def make_blockouts():
    """Placeholder low-poly variants, in the style of the current model, ready to be refined by hand."""
    arm, ref = rig(), body()
    existing = {o.name for o in bpy.data.objects}
    head_idx = ref.vertex_groups["head"].index

    def head_vertex(v):
        return any(g.group == head_idx and g.weight > 0.5 for g in v.groups)

    hlo, hhi = mesh_bounds(ref, head_vertex)
    hc, hr = (hlo + hhi) / 2, (hhi - hlo) / 2
    helmet = bpy.data.objects["Helmet_Default"]
    goggle = bpy.data.objects["Glasses_Default"]
    pack = bpy.data.objects["Backpack_Default"]
    vest = bpy.data.objects["Vest_Default"]

    # --- Helmet_Hood: shell around the head with a face opening, draped onto the neck.
    if "Helmet_Hood" not in existing:
        bm = bmesh.new()
        bmesh.ops.create_uvsphere(bm, u_segments=10, v_segments=7, radius=1.0)
        for v in bm.verts:
            v.co = Vector((v.co.x * hr.x * 1.22, v.co.y * hr.y * 1.22, v.co.z * hr.z * 1.12)) + hc + Vector((0, 0.008, 0.012))
        face = [f for f in bm.faces
                if f.calc_center_median().y < hc.y - 0.35 * hr.y
                and hc.z - 0.75 * hr.z < f.calc_center_median().z < hc.z + 0.5 * hr.z]
        bmesh.ops.delete(bm, geom=face, context="FACES")
        for v in bm.verts:  # drape the lower back down to the neck/shoulders
            if v.co.z < hc.z - 0.4 * hr.z and v.co.y > hc.y - 0.2 * hr.y:
                v.co.z -= 0.07
                v.co.y += 0.015
        bmesh.ops.solidify(bm, geom=bm.faces[:], thickness=0.008)
        hood = _new_mesh_object("Helmet_Hood", bm, helmet.data.materials[0], helmet)
        transfer_weights(hood, ref, "Helmet")

    # --- Glasses: thinner shades (scaled default) + a wrap-around visor band.
    if "Glasses_Shades" not in existing:
        glo, ghi = mesh_bounds(goggle)
        _scaled_copy("Glasses_Default", "Shades", (1.05, 1.0, 0.6), (glo + ghi) / 2)
    if "Glasses_Visor" not in existing:
        glo, ghi = mesh_bounds(goggle)
        zc, half_h = (glo.z + ghi.z) / 2, (ghi.z - glo.z) * 0.55
        bm = bmesh.new()
        ring_lo, ring_hi = [], []
        steps, arc = 8, math.radians(150)
        for i in range(steps + 1):
            a = -math.pi / 2 - arc / 2 + arc * i / steps  # centered on -Y (character front)
            x, y = math.cos(a) * hr.x * 1.12, math.sin(a) * hr.y * 1.15
            ring_lo.append(bm.verts.new((hc.x + x, hc.y + y, zc - half_h)))
            ring_hi.append(bm.verts.new((hc.x + x, hc.y + y, zc + half_h)))
        for i in range(steps):
            bm.faces.new((ring_lo[i], ring_lo[i + 1], ring_hi[i + 1], ring_hi[i]))
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
        bmesh.ops.solidify(bm, geom=bm.faces[:], thickness=0.006)
        visor = _new_mesh_object("Glasses_Visor", bm, goggle.data.materials[0], goggle)
        transfer_weights(visor, ref, "Glasses")

    # --- Backpack: small and large, scaled around the face that touches the back.
    plo, phi = mesh_bounds(pack)
    if "Backpack_Small" not in existing:
        _scaled_copy("Backpack_Default", "Small", (0.8, 0.65, 0.6), Vector(((plo.x + phi.x) / 2, plo.y, phi.z - 0.03)))
    if "Backpack_Large" not in existing:
        _scaled_copy("Backpack_Default", "Large", (1.12, 1.35, 1.3), Vector(((plo.x + phi.x) / 2, plo.y, phi.z)))

    # --- Vest_BeltPouches: belt ring fitted to the body at the waist + pouches.
    if "Vest_BeltPouches" not in existing:
        vlo, _vhi = mesh_bounds(vest)
        z0, z1 = vlo.z - 0.05, vlo.z + 0.005
        band = [ref.matrix_world @ v.co for v in ref.data.vertices if z0 - 0.03 < (ref.matrix_world @ v.co).z < z1 + 0.03]
        cy = sum(c.y for c in band) / len(band)
        sides = 12
        radius = []
        for i in range(sides):
            a = 2 * math.pi * i / sides
            best = 0.0
            for c in band:
                d = Vector((c.x, c.y - cy))
                if d.length > 1e-6 and math.cos(math.atan2(d.y, d.x) - a) > math.cos(math.pi / sides):
                    best = max(best, d.length)
            radius.append(best + 0.012)
        bm = bmesh.new()
        lo_r = [bm.verts.new((math.cos(2 * math.pi * i / sides) * radius[i], cy + math.sin(2 * math.pi * i / sides) * radius[i], z0)) for i in range(sides)]
        hi_r = [bm.verts.new((v.co.x, v.co.y, z1)) for v in lo_r]
        for i in range(sides):
            j = (i + 1) % sides
            bm.faces.new((lo_r[i], lo_r[j], hi_r[j], hi_r[i]))
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
        # Pouches: front-left, front-right, both hips, back.
        for deg in (-60, -120, 0, 180, 90):
            a = math.radians(deg)
            i = round(a / (2 * math.pi) * sides) % sides
            r = radius[i] + 0.022
            center = Vector((math.cos(a) * r, cy + math.sin(a) * r, (z0 + z1) / 2 - 0.012))
            res = bmesh.ops.create_cube(bm, size=1.0)
            for v in res["verts"]:
                v.co = Matrix.Translation(center) @ Matrix.Rotation(a + math.pi / 2, 4, "Z") @ Matrix.Diagonal((0.075, 0.04, 0.07, 1)) @ v.co
        belt = _new_mesh_object("Vest_BeltPouches", bm, vest.data.materials[0], vest)
        transfer_weights(belt, ref, "Vest")

    # Spec-ops accessories (masks, NVG, boonie, radio, chest rig...): see soldier_specops.py.
    import soldier_specops
    soldier_specops.make(sys.modules[__name__], TEXTURES_DIR)

    log("Blockouts ready.")


