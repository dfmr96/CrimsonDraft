"""
Soldier appearance variants pipeline (Blender 5.2).

Builds interchangeable equipment pieces (Helmet / Glasses / Backpack / Vest) skinned to the
SAME armature as SoldierCharacterRigged.fbx and exports them to a separate FBX
(SoldierCharacterRigged_Variants.fbx). The original FBX is only read, never re-exported.

Usage (headless):
    blender -b --factory-startup --python soldier_variants.py -- build [--force] [--no-blockouts]
    blender -b SoldierVariants.blend --python soldier_variants.py -- new-variant --from Helmet_Default --name Beret
    blender -b SoldierVariants.blend --python soldier_variants.py -- validate
    blender -b SoldierVariants.blend --python soldier_variants.py -- export

Inside Blender (Scripting tab) the same functions can be called directly:
    import sys; sys.path.append(r"<this folder>"); import soldier_variants as sv
    sv.new_variant("Vest_Default", "Plates"); sv.validate(); sv.export()
"""

