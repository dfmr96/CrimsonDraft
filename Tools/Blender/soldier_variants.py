def validate():
    arm = rig()
    bones = deform_bone_names(arm)
    errors = []
    objs = variant_objects()
    if not objs:
        errors.append("No variants found in Slot_* collections.")
    for slot in SLOTS:
        if slot not in OPTIONAL_DEFAULT_SLOTS and not bpy.data.objects.get(slot + "_Default"):
            errors.append("Slot %s has no %s_Default." % (slot, slot))
    for o in objs:
        tag = "'%s':" % o.name
        if slot_of(o.name) is None or o.users_collection[0].name != "Slot_" + slot_of(o.name):
            errors.append("%s name must be <Slot>_<Variant> and live in collection Slot_<Slot>." % tag)
        mods = [m for m in o.modifiers if m.type == "ARMATURE"]
        if len(mods) != 1 or mods[0].object != arm:
            errors.append("%s needs exactly one Armature modifier pointing at '%s'." % (tag, ARMATURE))
        if [m for m in o.modifiers if m.type != "ARMATURE"]:
            errors.append("%s has non-Armature modifiers (apply or remove them)." % tag)
        if o.parent != arm:
            errors.append("%s must be parented to '%s'." % (tag, ARMATURE))
        if not (o.matrix_basis == Matrix.Identity(4) and o.matrix_parent_inverse == Matrix.Identity(4)):
            errors.append("%s has unapplied transforms (location/rotation must be 0, scale 1)." % tag)
        if o.data.shape_keys:
            errors.append("%s has shape keys." % tag)
        unknown = [g.name for g in o.vertex_groups if g.name not in bones]
        if unknown:
            errors.append("%s vertex groups not in the rig: %s" % (tag, unknown))
        unweighted = sum(1 for v in o.data.vertices if not any(g.weight > 1e-4 for g in v.groups))
        if unweighted:
            errors.append("%s %d vertices without weights." % (tag, unweighted))
        over = sum(1 for v in o.data.vertices if sum(1 for g in v.groups if g.weight > 1e-4) > MAX_INFLUENCES)
        if over:
            errors.append("%s %d vertices with more than %d influences." % (tag, over, MAX_INFLUENCES))
        if not o.data.uv_layers:
            errors.append("%s has no UVs." % tag)
        for m in o.data.materials:
            if m and m.name not in ALLOWED_MATERIALS and not m.name.startswith("Mat_%s_" % slot_of(o.name)):
                errors.append("%s material '%s' should be one of %s or Mat_<Slot>_<Variant>." % (tag, m.name, ALLOWED_MATERIALS))
    if errors:
        raise PipelineError("Validation failed:\n  - " + "\n  - ".join(errors))
    log("Validation OK (%d variants: %s)" % (len(objs), ", ".join(o.name for o in objs)))


