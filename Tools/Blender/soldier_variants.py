# Helpers
# ---------------------------------------------------------------------------------------------
def rig():
    arm = bpy.data.objects.get(ARMATURE)
    if not arm or arm.type != "ARMATURE":
        raise PipelineError("Armature '%s' not found." % ARMATURE)
    return arm


def body():
    obj = bpy.data.objects.get(BODY)
    if not obj:
        raise PipelineError("Reference body '%s' not found." % BODY)
    return obj


def slot_of(name):
    slot = name.split("_", 1)[0]
    return slot if slot in SLOTS and "_" in name else None


def slot_collection(slot):
    name = "Slot_" + slot
    col = bpy.data.collections.get(name)
    if not col:
        col = bpy.data.collections.new(name)
        bpy.context.scene.collection.children.link(col)
    return col


def move_to_collection(obj, col):
    for c in list(obj.users_collection):
        c.objects.unlink(obj)
    col.objects.link(obj)


def variant_objects():
    """Every mesh named Slot_Variant inside a Slot_* collection."""
    out = []
    for slot in SLOTS:
        col = bpy.data.collections.get("Slot_" + slot)
        if col:
            out += [o for o in col.objects if o.type == "MESH"]
    return sorted(out, key=lambda o: o.name)


def bake_transform_into_mesh(obj, arm):
    """Puts the object exactly on the armature (identity local transform) keeping world vertices."""
    to_arm = arm.matrix_world.inverted() @ obj.matrix_world
    obj.data.transform(to_arm)
    if obj.parent != arm:
        obj.parent = arm
    obj.matrix_parent_inverse = Matrix.Identity(4)
    obj.matrix_basis = Matrix.Identity(4)


def ensure_armature_modifier(obj, arm):
    mods = [m for m in obj.modifiers if m.type == "ARMATURE"]
    for m in mods[1:]:
        obj.modifiers.remove(m)
    mod = mods[0] if mods else obj.modifiers.new("Armature", "ARMATURE")
    mod.object = arm
    mod.use_vertex_groups = True
    mod.use_bone_envelopes = False


def deform_bone_names(arm):
    return {b.name for b in arm.data.bones if b.use_deform}


def mesh_bounds(obj, vertex_filter=None):
    co = [obj.matrix_world @ v.co for v in obj.data.vertices if vertex_filter is None or vertex_filter(v)]
    if not co:
        raise PipelineError("No vertices to measure on '%s'." % obj.name)
    lo = Vector((min(c.x for c in co), min(c.y for c in co), min(c.z for c in co)))
    hi = Vector((max(c.x for c in co), max(c.y for c in co), max(c.z for c in co)))
    return lo, hi


def uv_rect(obj):
    """UV bounding box of a piece: blockouts reuse that patch of the atlas (same palette, no new material)."""
    uv = obj.data.uv_layers.active
    us = [d.uv.x for d in uv.data]
    vs = [d.uv.y for d in uv.data]
    return min(us), min(vs), max(us), max(vs)


