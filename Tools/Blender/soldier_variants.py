def rest_pose_of(fbx_path):
    """Imports an FBX in a scratch scene (leaf bones kept, as Unity sees them) and returns
    {bone: {parent, pos, rot}} in armature space."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.fbx(filepath=fbx_path, ignore_leaf_bones=False)
    arm = next(o for o in bpy.data.objects if o.type == "ARMATURE")
    out = {"__armature__": {"world": [list(r) for r in arm.matrix_world]}}
    for b in arm.data.bones:
        m = b.matrix_local
        out[b.name] = {"parent": b.parent.name if b.parent else None,
                       "pos": list(m.to_translation()), "rot": list(m.to_quaternion())}
    return out


def compare_rest_pose(a, b):
    errors = []
    for name in sorted(set(a) | set(b)):
        if name == "__armature__":
            continue
        if name not in b:
            errors.append("Bone '%s' missing in variants FBX." % name)
            continue
        if name not in a:
            errors.append("Bone '%s' does not exist in the original." % name)
            continue
        if a[name]["parent"] != b[name]["parent"]:
            errors.append("Bone '%s' parent %s != %s." % (name, a[name]["parent"], b[name]["parent"]))
        dp = (Vector(a[name]["pos"]) - Vector(b[name]["pos"])).length
        qa, qb = Vector(a[name]["rot"]), Vector(b[name]["rot"])
        if qa.dot(qb) < 0:
            qb = -qb
        # |qa - qb| = 2 sin(theta/4): numerically stable for tiny angles (acos of a dot ~1 is not).
        dr = math.degrees(4 * math.asin(min(1.0, (qa - qb).length / 2)))
        if dp > POS_TOL or dr > ROT_TOL_DEG:
            errors.append("Bone '%s' rest pose differs: %.6f m, %.4f deg." % (name, dp, dr))
    wa, wb = a["__armature__"]["world"], b["__armature__"]["world"]
    if max(abs(x - y) for ra, rb in zip(wa, wb) for x, y in zip(ra, rb)) > 1e-5:
        errors.append("Armature object transform differs.")
    return errors


# ---------------------------------------------------------------------------------------------
# Export
# ---------------------------------------------------------------------------------------------
def export():
    validate()
    arm = rig()
    bpy.ops.object.select_all(action="DESELECT")
    arm.select_set(True)
    for o in variant_objects():
        o.select_set(True)
    bpy.context.view_layer.objects.active = arm
    os.makedirs(os.path.dirname(EXPORT_FBX), exist_ok=True)
    bpy.ops.export_scene.fbx(filepath=EXPORT_FBX, **EXPORT_SETTINGS)
    log("Exported %s" % EXPORT_FBX)

    blend = bpy.data.filepath
    os.makedirs(REPORTS, exist_ok=True)
    original, variants = rest_pose_of(SOURCE_FBX), rest_pose_of(EXPORT_FBX)
    errors = compare_rest_pose(original, variants)
    for name, data in (("restpose_original.json", original), ("restpose_variants.json", variants)):
        with open(os.path.join(REPORTS, name), "w") as f:
            json.dump(data, f, indent=1)
    with open(os.path.join(REPORTS, "restpose_diff.json"), "w") as f:
        json.dump({"ok": not errors, "pos_tol_m": POS_TOL, "rot_tol_deg": ROT_TOL_DEG, "errors": errors}, f, indent=1)
    if blend:
        bpy.ops.wm.open_mainfile(filepath=blend)
    if errors:
        raise PipelineError("Rest pose validation FAILED (%d):\n  - %s" % (len(errors), "\n  - ".join(errors[:30])))
    log("Rest pose OK: %d bones match the original within %g m / %g deg." % (len(original) - 1, POS_TOL, ROT_TOL_DEG))


