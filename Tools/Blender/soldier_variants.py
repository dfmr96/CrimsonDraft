# Weights
# ---------------------------------------------------------------------------------------------
def transfer_weights(target, source, slot):
    """Data transfer (nearest face, poly-interpolated) of vertex-group weights, limited to the slot's
    bones, normalized and capped at MAX_INFLUENCES. Pure Python so it does not depend on operator context."""
    allowed = set(SLOT_BONES[slot])
    src_me = source.data
    src_me.calc_loop_triangles()
    src_mw = source.matrix_world
    verts = [src_mw @ v.co for v in src_me.vertices]
    tris = [tuple(t.vertices) for t in src_me.loop_triangles]
    tree = BVHTree.FromPolygons(verts, tris)
    src_names = {g.index: g.name for g in source.vertex_groups}

    def vweights(i):
        return {src_names[g.group]: g.weight for g in src_me.vertices[i].groups if src_names.get(g.group) in allowed}

    for g in list(target.vertex_groups):
        target.vertex_groups.remove(g)

    tmw = target.matrix_world
    per_vertex = []
    for v in target.data.vertices:
        p = tmw @ v.co
        loc, _n, tri_index, _d = tree.find_nearest(p)
        acc = {}
        if tri_index is not None:
            tri = tris[tri_index]
            bary = poly_3d_calc([verts[i] for i in tri], loc)
            for vi, b in zip(tri, bary):
                for name, w in vweights(vi).items():
                    acc[name] = acc.get(name, 0.0) + w * b
        acc = {k: w for k, w in acc.items() if w > 1e-4}
        if not acc:
            acc = {SLOT_FALLBACK_BONE[slot]: 1.0}
        top = sorted(acc.items(), key=lambda kv: -kv[1])[:MAX_INFLUENCES]
        total = sum(w for _k, w in top)
        per_vertex.append([(k, w / total) for k, w in top])

    groups = {}
    for i, weights in enumerate(per_vertex):
        for name, w in weights:
            vg = groups.get(name) or target.vertex_groups.new(name=name)
            groups[name] = vg
            vg.add([i], w, "REPLACE")


def limit_and_normalize(obj):
    names = {g.index: g.name for g in obj.vertex_groups}
    for v in obj.data.vertices:
        ws = sorted(((g.group, g.weight) for g in v.groups if g.weight > 1e-4), key=lambda x: -x[1])
        keep, drop = ws[:MAX_INFLUENCES], ws[MAX_INFLUENCES:]
        for gi, _w in drop:
            obj.vertex_groups[names[gi]].remove([v.index])
        total = sum(w for _g, w in keep)
        if total > 0:
            for gi, w in keep:
                obj.vertex_groups[names[gi]].add([v.index], w / total, "REPLACE")


