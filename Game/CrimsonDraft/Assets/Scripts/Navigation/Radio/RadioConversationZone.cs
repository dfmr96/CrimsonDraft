#nullable enable

using UnityEngine;
using VContainer;

namespace CrimsonDraft.Navigation.Radio
{
    /// <summary>
    /// A trigger volume that offers a radio call while the player is inside it. The call waits
    /// (HUD icon) until it is answered from the inventory, even if the player walks out, unless
    /// <see cref="withdrawOnExit"/> is set.
    /// </summary>
    [RequireComponent(typeof(Collider))]
    public sealed class RadioConversationZone : MonoBehaviour
    {
        [Tooltip("Yarn node to play, e.g. radio_01_adrift (generated by Tools/Dialogue/to-yarn.ps1).")]
        [SerializeField] private string nodeName = string.Empty;

        [Tooltip("Take the call back if the player leaves the area before answering it.")]
        [SerializeField] private bool withdrawOnExit;

        private IRadioConversationService? service;

        public string NodeName => this.nodeName;

        [Inject]
        public void Construct(IRadioConversationService service) => this.service = service;

        private void Reset()
        {
            if (TryGetComponent<Collider>(out var col)) col.isTrigger = true;
        }

        private void OnTriggerEnter(Collider other)
        {
            if (!other.CompareTag("Player")) return;
            this.service?.Offer(this.nodeName);
        }

        private void OnTriggerExit(Collider other)
        {
            if (!this.withdrawOnExit || !other.CompareTag("Player")) return;
            this.service?.Withdraw(this.nodeName);
        }

        private void OnDrawGizmos()
        {
            if (!TryGetComponent<Collider>(out var col)) return;
            Gizmos.color = new Color(0.37f, 0.83f, 0.63f, 0.25f);
            Gizmos.matrix = transform.localToWorldMatrix;
            switch (col)
            {
                case BoxCollider box:    Gizmos.DrawCube(box.center, box.size); break;
                case SphereCollider sph: Gizmos.DrawSphere(sph.center, sph.radius); break;
            }
        }
    }
}
